def earth_cell_tables():
    """Every committed Earth cell table (pilot, known-analog tiles, scan shards), sorted by name."""
    return sorted(glob.glob(os.path.join(EARTH_CELLS, "*.parquet")))


def ensure(*dirs):
    """Create folders if missing; returns the first one."""
    for d in dirs:
        os.makedirs(d, exist_ok=True)
    return dirs[0] if dirs else None


def rel(path):
    """Path relative to the repository root, with forward slashes (for manifests and docs)."""
    return os.path.relpath(path, ROOT).replace("\\", "/")
